/// <summary>
/// 1つのリールに対して「止まってよい角度」を持つクラス。
/// 
/// 20コマリールなら、基本は 18度刻みです。
/// 0, 18, 36, 54 ... 342 のように設定します。
/// 
/// 【ここをいじるとどうなる？】
/// stopAngles に入っている角度だけが、その役のときに停止候補になります。
/// 例：ベル成立時の左リール stopAngles を 0, 72, 144 だけにすると、左リールはその角度のどれかまで滑って止まります。
/// </summary>
[System.Serializable]
public class StopAngleList
{
    /// <summary>
    /// 停止してよい角度の一覧。
    /// 
    /// 角度は 0〜360 の範囲で考えます。
    /// 360 は 0 と同じ扱いなので、基本的には 0〜342 を使うのがおすすめです。
    /// </summary>
    public float[] stopAngles =
    {
        0f,
        18f,
        36f,
        54f,
        72f,
        90f,
        108f,
        126f,
        144f,
        162f,
        180f,
        198f,
        216f,
        234f,
        252f,
        270f,
        288f,
        306f,
        324f,
        342f
    };
}
